function sitemap() {
  const entries = [];
  const add = (loc, priority, changefreq, pair) => entries.push({loc, priority, changefreq, pair});
  add(SITE.origin + '/', '1.0', 'weekly', null);
  add(SITE.origin + '/portal/index.html', '0.9', 'weekly', null);
  const dirPair = {zh: dirUrl('zh'), en: dirUrl('en')};
  add(dirUrl('zh'), '0.8', 'weekly', dirPair);
  add(dirUrl('en'), '0.7', 'weekly', dirPair);
  for (const g of GAMES) {
    const pair = {zh: gameUrl(g, 'zh'), en: gameUrl(g, 'en')};
    add(pair.zh, '0.8', 'monthly', pair);
    add(pair.en, '0.7', 'monthly', pair);
  }
  for (const p of ['/shop.html', '/membership.html', '/terms.html', '/privacy.html', '/contact.html']) {
    add(SITE.origin + p, p === '/shop.html' ? '0.5' : '0.3', 'monthly', null);
  }
  const url = e => `  <url>\n    <loc>${esc(e.loc)}</loc>\n    <lastmod>${SITE.lastmod}</lastmod>\n    <changefreq>${e.changefreq}</changefreq>\n    <priority>${e.priority}</priority>${e.pair ? `\n    <xhtml:link rel="alternate" hreflang="zh-CN" href="${esc(e.pair.zh)}"/>\n    <xhtml:link rel="alternate" hreflang="en" href="${esc(e.pair.en)}"/>\n    <xhtml:link rel="alternate" hreflang="x-default" href="${esc(e.pair.zh)}"/>` : ''}\n  </url>`;
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${entries.map(url).join('\n')}
</urlset>
`;
}

