/* ------------------------------------------- synchronous ?game= head updater */
function metaScript() {
  const map = {};
  for (const g of GAMES) {
    map[g.id] = {
      zh: {title: g.title.zh, description: g.description.zh, keywords: g.keywords.zh, canonical: gameUrl(g, 'zh'), image: ogUrl(g), name: g.name.zh, locale: 'zh_CN'},
      en: {title: g.title.en, description: g.description.en, keywords: g.keywords.en, canonical: gameUrl(g, 'en'), image: ogUrl(g), name: g.name.en, locale: 'en_US'}
    };
  }
  return `/* Generated by scripts/build-game-seo.mjs — DO NOT EDIT.
   Included synchronously in <head> on the portal and table shells. A crawler
   that runs JS (and every share-preview fetcher that does not) gets the same
   per-game title, description, canonical and OG tags as the static landing
   pages. The canonical points at /games/<slug>/ so the ?game= query URL never
   competes with its landing page for the same search result. */
(function(){
 'use strict';
 var MAP=${JSON.stringify(map, null, 2)};
 function meta(attr,name,content){
  var el=document.head.querySelector('meta['+attr+'="'+name+'"]');
  if(!el){el=document.createElement('meta');el.setAttribute(attr,name);el.setAttribute('data-seo','1');document.head.appendChild(el);}
  el.setAttribute('content',content);
 }
 function canonical(href){
  var el=document.head.querySelector('link[rel="canonical"]');
  if(!el){el=document.createElement('link');el.setAttribute('rel','canonical');document.head.appendChild(el);}
  el.setAttribute('data-seo','1');el.setAttribute('href',href);
 }
 function alternate(lang,href){
  var el=document.head.querySelector('link[rel="alternate"][hreflang="'+lang+'"]');
  if(!el){el=document.createElement('link');el.setAttribute('rel','alternate');el.setAttribute('hreflang',lang);document.head.appendChild(el);}
  el.setAttribute('data-seo','1');el.setAttribute('href',href);
 }
 function structured(d){
  var el=document.head.querySelector('script[data-seo="game"]');
  if(!el){el=document.createElement('script');el.type='application/ld+json';el.setAttribute('data-seo','game');document.head.appendChild(el);}
  el.textContent=JSON.stringify({'@context':'https://schema.org','@type':'VideoGame','name':d.name,
   'description':d.description,'url':d.canonical,'image':d.image,'applicationCategory':'Game',
   'gamePlatform':'Web browser','isAccessibleForFree':true,
   'offers':{'@type':'Offer','price':'0','priceCurrency':'CNY'},
   'publisher':{'@type':'Organization','name':'JoyFlock','url':'${SITE.origin}/'}});
 }
 var expectedTitle=null;
 function setTitle(v){expectedTitle=v;if(document.title!==v)document.title=v;}
 function apply(){
  var id=new URLSearchParams(location.search).get('game');
  var item=MAP[id];if(!item)return;
  var lang=document.documentElement.getAttribute('data-locale')==='zh'?'zh':'en';
  var d=item[lang];
  setTitle(d.title);
  meta('name','description',d.description);
  meta('name','keywords',d.keywords);
  meta('property','og:type','website');
  meta('property','og:site_name','JoyFlock');
  meta('property','og:locale',d.locale);
  meta('property','og:title',d.title);
  meta('property','og:description',d.description);
  meta('property','og:url',d.canonical);
  meta('property','og:image',d.image);
  meta('property','og:image:width','${SITE.ogWidth}');
  meta('property','og:image:height','${SITE.ogHeight}');
  meta('name','twitter:card','summary_large_image');
  meta('name','twitter:title',d.title);
  meta('name','twitter:description',d.description);
  meta('name','twitter:image',d.image);
  canonical(d.canonical);
  alternate('zh-CN',item.zh.canonical);
  alternate('en',item.en.canonical);
  alternate('x-default',item.zh.canonical);
  structured(d);
 }
 apply();
 /* portal.js / table.js are deferred modules and rewrite document.title while
    they boot; one DOMContentLoaded pass restores the SEO title afterwards. */
 if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',apply,{once:true});
 /* /api/me resolves AFTER DOMContentLoaded and portal.js calls updateLanguage()
    again from its account-changed listener. Keep the SEO title authoritative on
    ?game= URLs without touching pages that have no game parameter. */
 if(typeof MutationObserver!=='undefined'){
  var titleNode=document.head.querySelector('title');
  if(titleNode)new MutationObserver(function(){
   if(expectedTitle&&document.title!==expectedTitle)document.title=expectedTitle;
  }).observe(titleNode,{childList:true,characterData:true,subtree:true});
  new MutationObserver(apply).observe(document.documentElement,
   {attributes:true,attributeFilter:['data-locale','lang']});
 }
 window.addEventListener('joyflock:account-changed',apply);
 window.addEventListener('storage',apply);
})();
`;
}

